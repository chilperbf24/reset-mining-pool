#!/usr/bin/env node
// Generates worker/backfill.sql + worker/seed.jsonl from the pool's
// CURRENT books (state/live-ledger.json + state/unclaimed.json) — the
// registry's historical seed. Run once at deploy time (see README.md);
// re-running regenerates the same files from whatever the books say then.
// Every number below is READ from the state files, never hand-typed, so
// the seed cannot drift from the ledger it describes.
import { readFileSync, writeFileSync } from 'node:fs';
import { fingerprint, splitTail } from '../lib/fpmatch.mjs';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const ledger = JSON.parse(readFileSync(`${ROOT}/state/live-ledger.json`, 'utf8'));
const unclaimed = JSON.parse(readFileSync(`${ROOT}/state/unclaimed.json`, 'utf8'));
const pool = ledger.pool_address;
const poolShort = `${pool.slice(0, 8)}…${pool.slice(-4)}`;

const rows = [];
const contribEvents = (ledger.events ?? []).filter(e => e.type === 'contribution');

// 1) Ledger contribution events, in order.
for (const ev of contribEvents) {
  const d = ev.data;
  const addr = d.address;
  const amount = BigInt(d.amount_units);
  if (d.source === 'manual-attribution') {
    const u = unclaimed.entries.find(e => e.id === d.unclaimed_id);
    rows.push({
      ts: u?.claimed_at ?? u?.detected_at ?? '2026-10-21T14:25:15.659Z',
      kind: 'import',
      address_hex: addr,
      planned_units: amount.toString(),
      fp_units: String(fingerprint(addr)),
      exact_units: amount.toString(),
      status: 'credited',
      source: 'operator',
      note: `运营者按用户确认人工导入（账本事件 #${ev.i} / manual-attribution）：该笔为无尾数整数到账（尾数 0、指纹认领通道无效），经用户确认来自此地址后走账本正规路径补记；fp_units 记此地址自身指纹 ${fingerprint(addr)} 供按地址/指纹检索`,
      ip_hash: null,
    });
  } else if (d.source === 'fingerprint-auto') {
    const tail = BigInt(d.fp_tail_units);
    rows.push({
      ts: d.detected_at,
      kind: 'auto_match',
      address_hex: addr,
      planned_units: (amount - tail).toString(),
      fp_units: tail.toString(),
      exact_units: amount.toString(),
      status: 'credited',
      source: 'matcher',
      note: `指纹自动对号入账（账本事件 #${ev.i} / fingerprint-auto）：到账尾数 ${tail} 在候选集中唯一命中此地址`,
      ip_hash: null,
    });
  }
}

// 2) Unclaimed history — every entry, open or claimed. A claimed entry
//    that already produced a contribution above is filed as history only
//    (status=claimed, note says so) so amounts are never double-counted.
for (const e of unclaimed.entries) {
  const amount = BigInt(e.amount_units);
  const { base } = splitTail(amount);
  const alreadyImported = contribEvents.some(ev => ev.data.unclaimed_id === e.id);
  rows.push({
    ts: e.detected_at,
    kind: 'unclaimed',
    address_hex: e.claimed_by ?? e.attributed_to ?? null,
    planned_units: base.toString(),
    fp_units: e.tail_units,
    exact_units: amount.toString(),
    status: e.status,
    source: 'matcher',
    note: e.id === 2 || BigInt(e.tail_units) === BigInt(fingerprint(pool))
      ? `尾数 ${e.tail_units} 经查为池子自身地址 ${poolShort} 的指纹——疑似有人以池地址在计算器误算金额后照数转账，发送钱包未知；金额已随池全额锁仓挖矿，挂待认领（unclaimed #${e.id}），待发送者凭其真实地址出现后核对处理`
      : (alreadyImported
        ? `指纹系统启用前已在池内的余额（待认领 #${e.id}，尾数 ${e.tail_units}）：已由运营者人工导入认领（见 import 记录，claimed_by=${e.claimed_by}，method=manual），本行为历史留痕、不重复计数`
        : `待认领 #${e.id}：${e.note ?? '无候选地址命中'}`),
    ip_hash: null,
  });
}

rows.sort((a, b) => (a.ts < b.ts ? -1 : a.ts > b.ts ? 1 : 0));

// seed.jsonl — one JSON object per line, same shape as the D1 rows.
writeFileSync(new URL('./seed.jsonl', import.meta.url),
  rows.map(r => JSON.stringify(r)).join('\n') + '\n');

// backfill.sql — plain INSERTs for `wrangler d1 execute --file`.
const esc = s => s === null || s === undefined ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`;
const sql = [
  '-- RESET pool registry — historical backfill (generated by gen-backfill.mjs',
  '-- from state/live-ledger.json + state/unclaimed.json; do not hand-edit).',
  '-- Idempotency: run ONCE against a fresh D1 (right after schema.sql).',
  ...rows.map(r => `INSERT INTO records (ts, kind, address_hex, planned_units, fp_units, exact_units, status, source, note, ip_hash) VALUES (${[r.ts, r.kind, r.address_hex, r.planned_units, r.fp_units, r.exact_units, r.status, r.source, r.note, r.ip_hash].map(esc).join(', ')});`),
  '',
].join('\n');
writeFileSync(new URL('./backfill.sql', import.meta.url), sql);
console.log(`backfill: ${rows.length} rows -> worker/backfill.sql + worker/seed.jsonl`);
for (const r of rows) console.log(`  ${r.ts} ${r.kind.padEnd(10)} addr=${r.address_hex ?? '—'} fp=${r.fp_units} exact=${r.exact_units} status=${r.status}`);
